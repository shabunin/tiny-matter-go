//go:build ignore

// gen_table regenerates p256_table.go from the Go standard library's
// crypto/internal/fips140/nistec/p256_table.go. Upstream stores the table as a
// [...]byte var aliased through unsafe, which TinyGo places in RAM (88 KB).
// We emit it as a [...]uint64 that is only ever indexed, so LLVM marks it
// read-only and it stays in flash; the uint64 form also avoids unaligned loads.
//
//	go run gen_table.go
package main

import (
	"bytes"
	"encoding/binary"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"regexp"
	"runtime"
	"strconv"
)

func main() {
	src, err := os.ReadFile(filepath.Join(runtime.GOROOT(), "src/crypto/internal/fips140/nistec/p256_table.go"))
	if err != nil {
		panic(err)
	}
	var blob []byte
	for _, m := range regexp.MustCompile(`0x[0-9a-f]+`).FindAll(src, -1) {
		v, err := strconv.ParseUint(string(m[2:]), 16, 8)
		if err != nil {
			panic(err)
		}
		blob = append(blob, byte(v))
	}
	const want = 43 * 32 * 2 * 4 * 8
	if len(blob) != want {
		panic(fmt.Sprintf("table has %d bytes, want %d", len(blob), want))
	}
	var b bytes.Buffer
	b.WriteString("// Code generated by gen_table.go from Go " + runtime.Version() + "; DO NOT EDIT.\n\n")
	b.WriteString("package nistec\n\n")
	b.WriteString("// p256Precomputed holds 43 tables of 32 affine multiples of G (x, y as\n")
	b.WriteString("// 4 Montgomery-domain limbs each). See p256SelectBase.\n")
	b.WriteString("var p256Precomputed = [43 * 32 * 8]uint64{\n")
	for i := 0; i < len(blob); i += 32 {
		b.WriteString("\t")
		for j := 0; j < 4; j++ {
			fmt.Fprintf(&b, "0x%016x, ", binary.LittleEndian.Uint64(blob[i+8*j:]))
		}
		b.WriteString("\n")
	}
	b.WriteString("}\n")
	out, err := format.Source(b.Bytes())
	if err != nil {
		panic(err)
	}
	if err := os.WriteFile("p256_table.go", out, 0o644); err != nil {
		panic(err)
	}
}
